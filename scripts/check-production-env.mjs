// Deployment preflight only: no network requests, credential output or .env loading.
import { isIP } from "node:net";

const errors = [];
const env = process.env;
function httpsOrigin(name) {
  const value = env[name];
  try {
    const url = new URL(value);
    const host = url.hostname.replace(/^\[|\]$/g, "");
    if (url.origin !== value || url.protocol !== "https:" || !host.includes(".") || isIP(host) ||
        /(?:^|\.)(?:localhost|local|test|invalid|example)$/.test(host) ||
        /(?:^|\.)example\.(?:com|org|net)$/.test(host)) throw new Error();
    return url;
  } catch { errors.push(`${name} must be a real public HTTPS origin without a path or trailing slash.`); }
}

if (Number(process.versions.node.split(".")[0]) !== 24) errors.push("Use Node.js 24.x.");
const supabase = httpsOrigin("NEXT_PUBLIC_SUPABASE_URL");
httpsOrigin("APP_ORIGIN");
const publicKey = env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY ?? "";
if (!/^sb_publishable_[A-Za-z0-9_-]+$/.test(publicKey)) errors.push("NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY must be the hosted project's publishable key.");
const serverKey = env.SUPABASE_SERVICE_ROLE_KEY ?? "";
let validServerKey = /^sb_secret_[A-Za-z0-9_-]+$/.test(serverKey);
if (!validServerKey) {
  try {
    const parts = serverKey.split(".");
    const payload = JSON.parse(Buffer.from(parts[1], "base64url").toString("utf8"));
    validServerKey = parts.length === 3 && payload.role === "service_role" && payload.iss === "supabase";
    if (payload.exp && payload.exp * 1000 <= Date.now()) validServerKey = false;
    if (supabase?.hostname.endsWith(".supabase.co") && payload.ref !== supabase.hostname.split(".")[0]) validServerKey = false;
  } catch { /* Report only the variable name, never token contents. */ }
}
if (!validServerKey || serverKey === publicKey) errors.push("SUPABASE_SERVICE_ROLE_KEY must be a hosted secret key or unexpired service-role JWT for this project.");
if (!env.AUTH_RATE_LIMIT_SECRET || env.AUTH_RATE_LIMIT_SECRET.trim().length < 43) errors.push("AUTH_RATE_LIMIT_SECRET must contain at least 32 randomly generated bytes encoded as hex or base64url.");
if (Object.keys(env).some((name) => name.startsWith("NEXT_PUBLIC_") && /SECRET|SERVICE_ROLE|PASSWORD|PRIVATE_KEY|STAFF_PIN/i.test(name))) {
  errors.push("Remove privileged credentials from NEXT_PUBLIC_ variables.");
}
if (errors.length) {
  console.error(`Production configuration is not ready:\n${errors.map((error) => `- ${error}`).join("\n")}`);
  process.exitCode = 1;
} else {
  console.log("Production environment format checks passed. Verify project/key pairing, migrations, Auth and Realtime in the hosted environment before launch.");
}
